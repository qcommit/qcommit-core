"""Create a public preview fixture with a native signer; never persist the secret key."""
import base64,hashlib,json,subprocess,tempfile,os
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
with tempfile.TemporaryDirectory() as d:
 p=Path(d);key=p/'key.pem'
 key.write_bytes(subprocess.check_output(['openssl','genpkey','-algorithm','SLH-DSA-SHA2-128s']))
 os.chmod(key,0o600)
 der=subprocess.check_output(['openssl','pkey','-in',str(key),'-pubout','-outform','DER'])
 assert der[:18].hex()=='3030300b0609608648016503040314032100'
 public=der[18:].hex()
 intent=dict(version=1,scope='preview-only',network='solana:devnet',creatorPublicKey=public,creatorLabel='Qcommit reference creator',
  fundingWallet='11111111111111111111111111111111',launchId=hashlib.sha256(b'qcommit public preview fixture').hexdigest(),
  name='Orbital',symbol='ORBT',description='A public, signed example for testing launch authorization. No token has been created.',
  metadataUri='',metadataSha256=None,decimals=6,supply='1000000000',recipient='11111111111111111111111111111111',mintAuthority='revoke',freezeAuthority='none',
  issuedAt='2026-10-10T20:00:00.000Z',expiresAt='2026-10-11T20:00:00.000Z')
 canonical=json.dumps(intent,separators=(',',':'),ensure_ascii=False).encode()
 message=hashlib.sha256(b'Qcommit/LaunchPreview/v1\0'+canonical).digest()
 (p/'message').write_bytes(message)
 sig=subprocess.check_output(['openssl','pkeyutl','-sign','-rawin','-inkey',str(key),'-in',str(p/'message'),'-pkeyopt','deterministic:0','-pkeyopt','context-string:Qcommit.LaunchPreview.v1'])
 assert len(sig)==7856
 receipt=dict(format='qcommit/launch-authorization/1',algorithm='SLH-DSA-SHA2-128s',context='Qcommit.LaunchPreview.v1',intent=intent,signature=base64.b64encode(sig).decode())
 (ROOT/'fixtures/orbital.receipt.json').write_text(json.dumps(receipt,indent=2)+'\n')
 (ROOT/'fixtures/creator-public-key.txt').write_text(public+'\n')
 (ROOT/'fixtures/PROVENANCE.json').write_text(json.dumps({'fixture':'orbital.receipt.json','source':'Generated by this script with native OpenSSL; not a NIST test vector.',
 'signer':subprocess.check_output(['openssl','version']).decode().strip(),'scope':'preview-only','sha256':hashlib.sha256((ROOT/'fixtures/orbital.receipt.json').read_bytes()).hexdigest(),'secretKey':'Generated in a temporary directory and removed. Never shipped.','fundingWallet':'All-ones system-program address is an explicit fixture placeholder; not a usable funding account.'},indent=2)+'\n')
 print(public)
